use strict;
use warnings;
use File::Spec;
use File::Temp qw(tempfile);
use Cwd qw(abs_path);
use POSIX;

# Get root directory
my $script_dir = dirname($0);
my $root_dir = abs_path(File::Spec->catdir($script_dir, '..'));
my $ios_dir = File::Spec->catdir($root_dir, 'apps', 'ios');
my $team_id_script = File::Spec->catfile($root_dir, 'scripts', 'ios-team-id.sh');
my $local_signing_file = File::Spec->catfile($ios_dir, '.local-signing.xcconfig');

sub dirname {
    my $path = shift;
    $path =~ s|/[^/]*$||;
    return $path;
}

sub sanitize_identifier_segment {
    my ($raw) = @_;
    $raw = lc($raw // '');
    $raw =~ s/[^a-z0-9]+/-/g;
    $raw =~ s/^-+//;
    $raw =~ s/-+$//;
    $raw =~ s/-+/-/g;
    return 'local' if !$raw;
    return $raw;
}

sub normalize_bundle_id {
    my ($raw) = @_;
    $raw = lc($raw // '');
    $raw =~ s/[^a-z0-9.\-]+/\-/g;
    $raw =~ s/\.\.+/\./g;
    $raw =~ s/^-+//;
    $raw =~ s/[.\-]+$//;
    return 'ai.openclaw.ios.test.local' if !$raw;
    return $raw;
}

# Check if team ID script exists and is executable
if (!-x $team_id_script) {
    print STDERR "ERROR: Missing team detection helper: $team_id_script\n";
    exit 1;
}

# Try to get team ID
my $team_id = '';
my $team_id_output = `$team_id_script 2>/dev/null`;
my $team_id_exit_code = $? >> 8;

if ($team_id_exit_code == 0) {
    chomp($team_id_output);
    $team_id = $team_id_output;
} else {
    if ($ENV{IOS_SIGNING_REQUIRED} && $ENV{IOS_SIGNING_REQUIRED} eq '1') {
        system($team_id_script);
        exit 1;
    }
    
    print STDERR "WARN: Unable to detect an Apple Team ID; keeping existing iOS signing override (if any).\n";
    exit 0;
}

# Determine identity source
my $identity_source;
if ($ENV{OPENCLAW_IOS_BUNDLE_SUFFIX}) {
    $identity_source = $ENV{OPENCLAW_IOS_BUNDLE_SUFFIX};
} else {
    $identity_source = $ENV{USER} // '';
    if (!$identity_source) {
        $identity_source = getpwuid($<) if defined(getpwuid($<));
    }
    my $team_segment = sanitize_identifier_segment($team_id);
    $identity_source .= "-$team_segment";
}
my $bundle_suffix = sanitize_identifier_segment($identity_source);

# Determine bundle base
my $bundle_base = $ENV{OPENCLAW_IOS_APP_BUNDLE_ID} // $ENV{OPENCLAW_IOS_BUNDLE_ID_BASE} // '';
if (!$bundle_base) {
    $bundle_base = "ai.openclaw.ios.test.$bundle_suffix";
}
$bundle_base = normalize_bundle_id($bundle_base);

# Determine other bundle IDs
my $share_bundle_id = $ENV{OPENCLAW_IOS_SHARE_BUNDLE_ID} // "$bundle_base.share";
my $activity_widget_bundle_id = $ENV{OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID} // "$bundle_base.activitywidget";
my $watch_app_bundle_id = $ENV{OPENCLAW_IOS_WATCH_APP_BUNDLE_ID} // "$bundle_base.watchkitapp";
my $watch_extension_bundle_id = $ENV{OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID} // "$watch_app_bundle_id.extension";

# Determine profiles
my $code_sign_style = $ENV{OPENCLAW_IOS_CODE_SIGN_STYLE} // 'Automatic';
my $app_profile = $ENV{OPENCLAW_IOS_APP_PROFILE} // '';
my $share_profile = $ENV{OPENCLAW_IOS_SHARE_PROFILE} // '';
my $watch_app_profile = $ENV{OPENCLAW_IOS_WATCH_APP_PROFILE} // '';
my $watch_extension_profile = $ENV{OPENCLAW_IOS_WATCH_EXTENSION_PROFILE} // '';

# Create temp file with configuration
my ($fh, $tmp_file) = tempfile('openclaw-ios-signing.XXXXXX', DIR => $ENV{TMPDIR} // '/tmp', UNLINK => 0);
print $fh <<EOF;
// Auto-generated by scripts/ios-configure-signing.sh.
// This file is local-only and should not be committed.
// Override values with env vars if needed:
// OPENCLAW_IOS_APP_BUNDLE_ID / OPENCLAW_IOS_BUNDLE_ID_BASE
// OPENCLAW_IOS_SHARE_BUNDLE_ID / OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID
// OPENCLAW_IOS_WATCH_APP_BUNDLE_ID / OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID
// OPENCLAW_IOS_CODE_SIGN_STYLE / OPENCLAW_IOS_APP_PROFILE / OPENCLAW_IOS_SHARE_PROFILE
// OPENCLAW_IOS_WATCH_APP_PROFILE / OPENCLAW_IOS_WATCH_EXTENSION_PROFILE
OPENCLAW_CODE_SIGN_STYLE = $code_sign_style
OPENCLAW_DEVELOPMENT_TEAM = $team_id
// Keep legacy key for compatibility with older signing config paths.
OPENCLAW_IOS_SELECTED_TEAM = $team_id
OPENCLAW_APP_BUNDLE_ID = $bundle_base
OPENCLAW_SHARE_BUNDLE_ID = $share_bundle_id
OPENCLAW_ACTIVITY_WIDGET_BUNDLE_ID = $activity_widget_bundle_id
OPENCLAW_WATCH_APP_BUNDLE_ID = $watch_app_bundle_id
OPENCLAW_WATCH_EXTENSION_BUNDLE_ID = $watch_extension_bundle_id
OPENCLAW_APP_PROFILE = $app_profile
OPENCLAW_SHARE_PROFILE = $share_profile
OPENCLAW_WATCH_APP_PROFILE = $watch_app_profile
OPENCLAW_WATCH_EXTENSION_PROFILE = $watch_extension_profile
EOF
close $fh;

# Check if file already exists and is identical
if (-f $local_signing_file) {
    open(my $existing_fh, '<', $local_signing_file) or die "Cannot open $local_signing_file: $!";
    open(my $new_fh, '<', $tmp_file) or die "Cannot open $tmp_file: $!";
    
    my $identical = 1;
    while (my $line1 = <$existing_fh>) {
        my $line2 = <$new_fh>;
        if (!defined($line2) || $line1 ne $line2) {
            $identical = 0;
            last;
        }
    }
    
    # Check if new file has more content
    if ($identical) {
        my $extra_content = <$new_fh>;
        $identical = 0 if defined($extra_content);
    }
    
    close $existing_fh;
    close $new_fh;
    
    if ($identical) {
        unlink $tmp_file;
        print "iOS signing config already up to date: team=$team_id app=$bundle_base\n";
        exit 0;
    }
}

# Move temp file to destination
rename($tmp_file, $local_signing_file) or die "Cannot move $tmp_file to $local_signing_file: $!";
print "Configured iOS signing: team=$team_id app=$bundle_base\n";
