import { spawnSync } from 'child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync, symlinkSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const usage = () => {
  console.log(`Usage:
  scripts/ios-write-version-xcconfig.js [--build-number 7]

Writes apps/ios/build/Version.xcconfig from apps/ios/version.json:
- OPENCLAW_IOS_VERSION = exact canonical iOS version
- OPENCLAW_MARKETING_VERSION = short iOS/App Store version
- OPENCLAW_BUILD_VERSION = explicit build number or local numeric fallback`);
};

const ROOT_DIR = resolve(join(__dirname, '..'));
const IOS_DIR = join(ROOT_DIR, 'apps', 'ios');
const BUILD_DIR = join(IOS_DIR, 'build');
const VERSION_XCCONFIG = join(BUILD_DIR, 'Version.xcconfig');
const VERSION_HELPER = join(ROOT_DIR, 'scripts', 'ios-version.ts');

let IOS_VERSION = '';
let MARKETING_VERSION = '';
let BUILD_NUMBER = '';

const prepare_build_dir = () => {
  if (existsSync(BUILD_DIR) && require('fs').lstatSync(BUILD_DIR).isSymbolicLink()) {
    console.error(`Refusing to use symlinked build directory: ${BUILD_DIR}`);
    process.exit(1);
  }
  
  mkdirSync(BUILD_DIR, { recursive: true });
};

const write_generated_file = (output_path, content) => {
  if (existsSync(output_path) && require('fs').lstatSync(output_path).isSymbolicLink()) {
    console.error(`Refusing to overwrite symlinked file: ${output_path}`);
    process.exit(1);
  }
  
  writeFileSync(output_path, content, 'utf8');
};

const args = process.argv.slice(2);
while (args.length > 0) {
  const arg = args.shift();
  switch (arg) {
    case '--':
      break;
    case '--build-number':
      BUILD_NUMBER = args.shift() || '';
      break;
    case '-h':
    case '--help':
      usage();
      process.exit(0);
      break;
    default:
      if (arg.startsWith('-')) {
        console.error(`Unknown argument: ${arg}`);
        usage();
        process.exit(1);
      }
      break;
  }
}

const getVersionInfo = () => {
  const child = spawnSync('node', ['--import', 'tsx', VERSION_HELPER, '--shell'], {
    cwd: ROOT_DIR,
    encoding: 'utf8'
  });
  
  if (child.status !== 0) {
    console.error(child.stderr);
    process.exit(1);
  }
  
  const lines = child.stdout.trim().split('\n');
  for (const line of lines) {
    const [key, value] = line.split('=');
    switch (key?.trim()) {
      case 'OPENCLAW_IOS_VERSION':
        IOS_VERSION = value?.trim() || '';
        break;
      case 'OPENCLAW_MARKETING_VERSION':
        MARKETING_VERSION = value?.trim() || '';
        break;
    }
  }
};

getVersionInfo();

if (!IOS_VERSION || !MARKETING_VERSION) {
  console.error(`Unable to resolve iOS version metadata from ${join(ROOT_DIR, 'apps', 'ios', 'version.json')}.`);
  process.exit(1);
}

if (!BUILD_NUMBER) {
  try {
    const gitResult = spawnSync('git', ['rev-list', '--count', 'HEAD'], {
      cwd: ROOT_DIR,
      encoding: 'utf8'
    });
    
    if (gitResult.status === 0) {
      BUILD_NUMBER = gitResult.stdout.trim();
    } else {
      BUILD_NUMBER = '0';
    }
  } catch (error) {
    BUILD_NUMBER = '0';
  }
}

if (!/^[0-9]+$/.test(BUILD_NUMBER)) {
  console.error(`Invalid build number '${BUILD_NUMBER}'. Expected digits only.`);
  process.exit(1);
}

prepare_build_dir();

const content = `// Auto-generated by scripts/ios-write-version-xcconfig.js.
// Local version override; do not commit.
OPENCLAW_IOS_VERSION = ${IOS_VERSION}
OPENCLAW_MARKETING_VERSION = ${MARKETING_VERSION}
OPENCLAW_BUILD_VERSION = ${BUILD_NUMBER}
`;

write_generated_file(VERSION_XCCONFIG, content);

console.log(`Prepared iOS version settings: ios=${IOS_VERSION} marketing=${MARKETING_VERSION} build=${BUILD_NUMBER}`);
