import { spawnSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');
const IOS_DIR = path.join(ROOT_DIR, 'apps', 'ios');
const TEAM_ID_SCRIPT = path.join(ROOT_DIR, 'scripts', 'ios-team-id.sh');
const LOCAL_SIGNING_FILE = path.join(IOS_DIR, '.local-signing.xcconfig');

function sanitizeIdentifierSegment(raw = '') {
  let result = raw.toLowerCase();
  result = result.replace(/[^a-z0-9]+/g, '-');
  result = result.replace(/^-+/, '');
  result = result.replace(/-+$/, '');
  result = result.replace(/-+/g, '-');
  if (result === '') {
    result = 'local';
  }
  return result;
}

function normalizeBundleId(raw = '') {
  let result = raw.toLowerCase();
  result = result.replace(/[^a-z0-9.-]+/g, '-');
  result = result.replace(/\.+/g, '.');
  result = result.replace(/^-+/, '');
  result = result.replace(/[.-]+$/, '');
  if (result === '') {
    result = 'ai.openclaw.ios.test.local';
  }
  return result;
}

if (!fs.existsSync(TEAM_ID_SCRIPT) || !fs.statSync(TEAM_ID_SCRIPT).mode & fs.constants.S_IXUSR) {
  console.error(`ERROR: Missing team detection helper: ${TEAM_ID_SCRIPT}`);
  process.exit(1);
}

let teamId = '';
try {
  const result = spawnSync(TEAM_ID_SCRIPT, { stdio: ['pipe', 'pipe', 'ignore'] });
  if (result.status === 0) {
    teamId = result.stdout.toString().trim();
  } else {
    throw new Error('Team ID script failed');
  }
} catch (error) {
  if (process.env.IOS_SIGNING_REQUIRED === '1') {
    const result = spawnSync(TEAM_ID_SCRIPT, { stdio: 'inherit' });
    process.exit(result.status || 1);
  }

  console.warn('WARN: Unable to detect an Apple Team ID; keeping existing iOS signing override (if any).');
  process.exit(0);
}

let identitySource = '';
if (process.env.OPENCLAW_IOS_BUNDLE_SUFFIX) {
  identitySource = process.env.OPENCLAW_IOS_BUNDLE_SUFFIX;
} else {
  identitySource = process.env.USER || '';
  if (!identitySource) {
    try {
      const idResult = spawnSync('id', ['-un'], { encoding: 'utf8' });
      if (idResult.status === 0) {
        identitySource = idResult.stdout.trim();
      }
    } catch (e) {
      // ignore error
    }
  }
  const teamSegment = sanitizeIdentifierSegment(teamId);
  identitySource = `${identitySource}-${teamSegment}`;
}
const bundleSuffix = sanitizeIdentifierSegment(identitySource);

let bundleBase = process.env.OPENCLAW_IOS_APP_BUNDLE_ID || process.env.OPENCLAW_IOS_BUNDLE_ID_BASE || '';
if (!bundleBase) {
  bundleBase = `ai.openclaw.ios.test.${bundleSuffix}`;
}
bundleBase = normalizeBundleId(bundleBase);

const shareBundleId = process.env.OPENCLAW_IOS_SHARE_BUNDLE_ID || `${bundleBase}.share`;
const activityWidgetBundleId = process.env.OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID || `${bundleBase}.activitywidget`;
const watchAppBundleId = process.env.OPENCLAW_IOS_WATCH_APP_BUNDLE_ID || `${bundleBase}.watchkitapp`;
const watchExtensionBundleId = process.env.OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID || `${watchAppBundleId}.extension`;

const codeSignStyle = process.env.OPENCLAW_IOS_CODE_SIGN_STYLE || 'Automatic';
const appProfile = process.env.OPENCLAW_IOS_APP_PROFILE || '';
const shareProfile = process.env.OPENCLAW_IOS_SHARE_PROFILE || '';
const watchAppProfile = process.env.OPENCLAW_IOS_WATCH_APP_PROFILE || '';
const watchExtensionProfile = process.env.OPENCLAW_IOS_WATCH_EXTENSION_PROFILE || '';

const tmpFile = path.join(os.tmpdir(), `openclaw-ios-signing-${Math.random().toString(36).substring(2, 15)}.xcconfig`);

const content = `// Auto-generated by scripts/ios-configure-signing.sh.
// This file is local-only and should not be committed.
// Override values with env vars if needed:
// OPENCLAW_IOS_APP_BUNDLE_ID / OPENCLAW_IOS_BUNDLE_ID_BASE
// OPENCLAW_IOS_SHARE_BUNDLE_ID / OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID
// OPENCLAW_IOS_WATCH_APP_BUNDLE_ID / OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID
// OPENCLAW_IOS_CODE_SIGN_STYLE / OPENCLAW_IOS_APP_PROFILE / OPENCLAW_IOS_SHARE_PROFILE
// OPENCLAW_IOS_WATCH_APP_PROFILE / OPENCLAW_IOS_WATCH_EXTENSION_PROFILE
OPENCLAW_CODE_SIGN_STYLE = ${codeSignStyle}
OPENCLAW_DEVELOPMENT_TEAM = ${teamId}
// Keep legacy key for compatibility with older signing config paths.
OPENCLAW_IOS_SELECTED_TEAM = ${teamId}
OPENCLAW_APP_BUNDLE_ID = ${bundleBase}
OPENCLAW_SHARE_BUNDLE_ID = ${shareBundleId}
OPENCLAW_ACTIVITY_WIDGET_BUNDLE_ID = ${activityWidgetBundleId}
OPENCLAW_WATCH_APP_BUNDLE_ID = ${watchAppBundleId}
OPENCLAW_WATCH_EXTENSION_BUNDLE_ID = ${watchExtensionBundleId}
OPENCLAW_APP_PROFILE = ${appProfile}
OPENCLAW_SHARE_PROFILE = ${shareProfile}
OPENCLAW_WATCH_APP_PROFILE = ${watchAppProfile}
OPENCLAW_WATCH_EXTENSION_PROFILE = ${watchExtensionProfile}
`;

fs.writeFileSync(tmpFile, content);

if (fs.existsSync(LOCAL_SIGNING_FILE)) {
  const currentContent = fs.readFileSync(LOCAL_SIGNING_FILE, 'utf8');
  if (currentContent === content) {
    fs.unlinkSync(tmpFile);
    console.log(`iOS signing config already up to date: team=${teamId} app=${bundleBase}`);
    process.exit(0);
  }
}

fs.renameSync(tmpFile, LOCAL_SIGNING_FILE);
console.log(`Configured iOS signing: team=${teamId} app=${bundleBase}`);
