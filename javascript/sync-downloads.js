/** Install a prepared artifact set and derive the site's checksums from its bytes. */
import fs from 'fs';
import path from 'path';
import { createHash } from 'crypto';
import { fileURLToPath } from 'url';
import yargs from 'yargs';
import { hideBin } from 'yargs/helpers';
import JSZip from 'jszip';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const argv = yargs(hideBin(process.argv))
  .option('from-dir', {
    type: 'string',
    demandOption: true,
    describe: 'Source directory'
  })
  .argv;

const site = path.resolve(__dirname, '../..');
const manifestPath = path.join(site, '..', 'plugin-source', 'browser-extension', 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const version = manifest.version;

const kinds = [
  ['extension', ''],
  ['plugin', ''],
  ['service', ''],
  ['android', '-source'],
  ['ios', '-source']
];

let names = kinds.map(([kind, suffix]) => 
  `tiktok-live-companion-${kind}-${version}${suffix}.zip`
);

const apkName = `tiktok-live-companion-android-${version}.apk`;
const apkPath = path.join(argv.fromDir, apkName);
if (fs.existsSync(apkPath)) {
  names.push(apkName);
}

// Verify ZIP files
for (const name of names) {
  const src = path.join(argv.fromDir, name);
  const data = fs.readFileSync(src);
  const zip = new JSZip();
  
  await zip.loadAsync(data).then(async (z) => {
    // Test ZIP integrity by trying to read all entries
    for (const [relativePath, zipEntry] of Object.entries(z.files)) {
      try {
        await zipEntry.async('nodebuffer');
      } catch (error) {
        throw new Error(`Corrupt ZIP: ${name}`);
      }
    }
    
    // Check manifest version for extension files
    if (name.includes('extension') && z.file('manifest.json')) {
      const manifestContent = await z.file('manifest.json').async('string');
      const manifestJson = JSON.parse(manifestContent);
      if (manifestJson.version !== version) {
        throw new Error('Manifest version mismatch');
      }
    }
  });
}

// Copy files
const downloadsDir = path.join(site, 'public', 'downloads');
if (!fs.existsSync(downloadsDir)) {
  fs.mkdirSync(downloadsDir, { recursive: true });
}

for (const name of names) {
  const src = path.join(argv.fromDir, name);
  const dest = path.join(downloadsDir, name);
  fs.copyFileSync(src, dest);
}

// Generate hashes
let hashes = '';
for (const name of names) {
  const filePath = path.join(downloadsDir, name);
  const fileBuffer = fs.readFileSync(filePath);
  const hashSum = createHash('sha256');
  hashSum.update(fileBuffer);
  const hex = hashSum.digest('hex');
  hashes += `${hex}  ${name}\n`;
}

// Write checksum file
const checksumFileName = `tiktok-live-companion-${version}-SHA256.txt`;
const checksumFilePath = path.join(downloadsDir, checksumFileName);
fs.writeFileSync(checksumFilePath, hashes, 'utf8');

// Write TypeScript file
const tsContent = `// Generated by site/scripts/sync-downloads.py; do not edit by hand.\nexport const downloadChecksums = ${JSON.stringify(hashes)};\n`;
const tsPath = path.join(site, 'src', 'download-checksums.ts');
fs.writeFileSync(tsPath, tsContent, 'utf8');

console.log(hashes);
