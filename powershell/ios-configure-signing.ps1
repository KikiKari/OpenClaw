$ErrorActionPreference = "Stop"

$ROOT_DIR = Join-Path $PSScriptRoot ".." | Resolve-Path
$IOS_DIR = Join-Path $ROOT_DIR "apps" "ios"
$TEAM_ID_SCRIPT = Join-Path $ROOT_DIR "scripts" "ios-team-id.sh"
$LOCAL_SIGNING_FILE = Join-Path $IOS_DIR ".local-signing.xcconfig"

function sanitize_identifier_segment {
    param(
        [string]$raw = ""
    )
    
    $raw = $raw.ToLower()
    $raw = $raw -replace "[^a-z0-9]+", "-"
    $raw = $raw -replace "^-+", ""
    $raw = $raw -replace "-+$", ""
    $raw = $raw -replace "-+", "-"
    
    if ([string]::IsNullOrEmpty($raw)) {
        $raw = "local"
    }
    
    return $raw
}

function normalize_bundle_id {
    param(
        [string]$raw = ""
    )
    
    $raw = $raw.ToLower()
    $raw = $raw -replace "[^a-z0-9.-]+", "-"
    $raw = $raw -replace "\.+", "."
    $raw = $raw -replace "^-+", ""
    $raw = $raw -replace "[.-]+$", ""
    
    if ([string]::IsNullOrEmpty($raw)) {
        $raw = "ai.openclaw.ios.test.local"
    }
    
    return $raw
}

if (-not (Test-Path $TEAM_ID_SCRIPT) -or -not (Get-Command $TEAM_ID_SCRIPT -ErrorAction SilentlyContinue)) {
    Write-Error "ERROR: Missing team detection helper: $TEAM_ID_SCRIPT"
    exit 1
}

$team_id = ""
try {
    $team_id = & $TEAM_ID_SCRIPT 2>$null
} catch {
    if ($env:IOS_SIGNING_REQUIRED -eq "1") {
        & $TEAM_ID_SCRIPT
        exit 1
    }
    
    Write-Warning "Unable to detect an Apple Team ID; keeping existing iOS signing override (if any)."
    exit 0
}

if (![string]::IsNullOrEmpty($env:OPENCLAW_IOS_BUNDLE_SUFFIX)) {
    $identity_source = $env:OPENCLAW_IOS_BUNDLE_SUFFIX
} else {
    $identity_source = $env:USER
    if ([string]::IsNullOrEmpty($identity_source)) {
        try {
            $identity_source = whoami
        } catch {
            $identity_source = ""
        }
    }
    $team_segment = sanitize_identifier_segment $team_id
    $identity_source = "$identity_source-$team_segment"
}
$bundle_suffix = sanitize_identifier_segment $identity_source

$bundle_base = $env:OPENCLAW_IOS_APP_BUNDLE_ID
if ([string]::IsNullOrEmpty($bundle_base)) {
    $bundle_base = $env:OPENCLAW_IOS_BUNDLE_ID_BASE
}
if ([string]::IsNullOrEmpty($bundle_base)) {
    $bundle_base = "ai.openclaw.ios.test.$bundle_suffix"
}
$bundle_base = normalize_bundle_id $bundle_base

$share_bundle_id = $env:OPENCLAW_IOS_SHARE_BUNDLE_ID
if ([string]::IsNullOrEmpty($share_bundle_id)) {
    $share_bundle_id = "$bundle_base.share"
}

$activity_widget_bundle_id = $env:OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID
if ([string]::IsNullOrEmpty($activity_widget_bundle_id)) {
    $activity_widget_bundle_id = "$bundle_base.activitywidget"
}

$watch_app_bundle_id = $env:OPENCLAW_IOS_WATCH_APP_BUNDLE_ID
if ([string]::IsNullOrEmpty($watch_app_bundle_id)) {
    $watch_app_bundle_id = "$bundle_base.watchkitapp"
}

$watch_extension_bundle_id = $env:OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID
if ([string]::IsNullOrEmpty($watch_extension_bundle_id)) {
    $watch_extension_bundle_id = "$watch_app_bundle_id.extension"
}

$code_sign_style = $env:OPENCLAW_IOS_CODE_SIGN_STYLE
if ([string]::IsNullOrEmpty($code_sign_style)) {
    $code_sign_style = "Automatic"
}

$app_profile = $env:OPENCLAW_IOS_APP_PROFILE
$share_profile = $env:OPENCLAW_IOS_SHARE_PROFILE
$watch_app_profile = $env:OPENCLAW_IOS_WATCH_APP_PROFILE
$watch_extension_profile = $env:OPENCLAW_IOS_WATCH_EXTENSION_PROFILE

$tmp_dir = $env:TMPDIR
if ([string]::IsNullOrEmpty($tmp_dir)) {
    $tmp_dir = "/tmp"
}
$tmp_file = [System.IO.Path]::GetTempFileName()

$content = @"
// Auto-generated by scripts/ios-configure-signing.sh.
// This file is local-only and should not be committed.
// Override values with env vars if needed:
// OPENCLAW_IOS_APP_BUNDLE_ID / OPENCLAW_IOS_BUNDLE_ID_BASE
// OPENCLAW_IOS_SHARE_BUNDLE_ID / OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID
// OPENCLAW_IOS_WATCH_APP_BUNDLE_ID / OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID
// OPENCLAW_IOS_CODE_SIGN_STYLE / OPENCLAW_IOS_APP_PROFILE / OPENCLAW_IOS_SHARE_PROFILE
// OPENCLAW_IOS_WATCH_APP_PROFILE / OPENCLAW_IOS_WATCH_EXTENSION_PROFILE
OPENCLAW_CODE_SIGN_STYLE = $code_sign_style
OPENCLAW_DEVELOPMENT_TEAM = $team_id
// Keep legacy key for compatibility with older signing config paths.
OPENCLAW_IOS_SELECTED_TEAM = $team_id
OPENCLAW_APP_BUNDLE_ID = $bundle_base
OPENCLAW_SHARE_BUNDLE_ID = $share_bundle_id
OPENCLAW_ACTIVITY_WIDGET_BUNDLE_ID = $activity_widget_bundle_id
OPENCLAW_WATCH_APP_BUNDLE_ID = $watch_app_bundle_id
OPENCLAW_WATCH_EXTENSION_BUNDLE_ID = $watch_extension_bundle_id
OPENCLAW_APP_PROFILE = $app_profile
OPENCLAW_SHARE_PROFILE = $share_profile
OPENCLAW_WATCH_APP_PROFILE = $watch_app_profile
OPENCLAW_WATCH_EXTENSION_PROFILE = $watch_extension_profile
"@

Set-Content -Path $tmp_file -Value $content

if (Test-Path $LOCAL_SIGNING_FILE) {
    $existing_content = Get-Content -Path $LOCAL_SIGNING_FILE -Raw
    if ($existing_content -eq $content) {
        Remove-Item -Path $tmp_file -Force
        Write-Output "iOS signing config already up to date: team=$team_id app=$bundle_base"
        exit 0
    }
}

Move-Item -Path $tmp_file -Destination $LOCAL_SIGNING_FILE -Force
Write-Output "Configured iOS signing: team=$team_id app=$bundle_base"
