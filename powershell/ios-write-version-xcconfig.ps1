using namespace System.IO

function usage {
@'
Usage:
  scripts/ios-write-version-xcconfig.ps1 [--build-number 7]

Writes apps/ios/build/Version.xcconfig from apps/ios/version.json:
- OPENCLAW_IOS_VERSION = exact canonical iOS version
- OPENCLAW_MARKETING_VERSION = short iOS/App Store version
- OPENCLAW_BUILD_VERSION = explicit build number or local numeric fallback
'@
}

$ROOT_DIR = (Get-Item $PSScriptRoot).Parent.FullName
$IOS_DIR = Join-Path $ROOT_DIR "apps/ios"
$BUILD_DIR = Join-Path $IOS_DIR "build"
$VERSION_XCCONFIG = Join-Path $BUILD_DIR "Version.xcconfig"
$VERSION_HELPER = Join-Path $ROOT_DIR "scripts/ios-version.ts"
$IOS_VERSION = $null
$MARKETING_VERSION = $null
$BUILD_NUMBER = $null

function prepare_build_dir {
    if ((Get-Item $BUILD_DIR -ErrorAction SilentlyContinue).LinkType -eq "SymbolicLink") {
        Write-Error "Refusing to use symlinked build directory: $BUILD_DIR"
        exit 1
    }

    New-Item -ItemType Directory -Path $BUILD_DIR -Force | Out-Null
}

function write_generated_file {
    param($output_path)
    
    if ((Get-Item $output_path -ErrorAction SilentlyContinue).LinkType -eq "SymbolicLink") {
        Write-Error "Refusing to overwrite symlinked file: $output_path"
        exit 1
    }

    $tmp_file = [Path]::GetTempFileName()
    $input | Set-Content -Path $tmp_file
    Move-Item -Path $tmp_file -Destination $output_path -Force
}

$args_queue = [Collections.Queue]::new($args)
while ($args_queue.Count -gt 0) {
    $arg = $args_queue.Dequeue()
    switch ($arg) {
        "--" { break }
        "--build-number" {
            if ($args_queue.Count -eq 0) {
                Write-Error "Missing value for --build-number"
                usage
                exit 1
            }
            $BUILD_NUMBER = $args_queue.Dequeue()
        }
        { @("-h", "--help") -contains $_ } {
            usage
            exit 0
        }
        default {
            Write-Error "Unknown argument: $arg"
            usage
            exit 1
        }
    }
}

Push-Location $ROOT_DIR
try {
    $version_output = node --import tsx $VERSION_HELPER --shell
    $version_output -split "`n" | ForEach-Object {
        if ($_ -match '^([^=]+)=(.*)$') {
            $key = $matches[1].Trim()
            $value = $matches[2].Trim()
            switch ($key) {
                "OPENCLAW_IOS_VERSION" { $IOS_VERSION = $value }
                "OPENCLAW_MARKETING_VERSION" { $MARKETING_VERSION = $value }
            }
        }
    }
}
finally {
    Pop-Location
}

if ([string]::IsNullOrEmpty($IOS_VERSION) -or [string]::IsNullOrEmpty($MARKETING_VERSION)) {
    Write-Error "Unable to resolve iOS version metadata from $ROOT_DIR/apps/ios/version.json."
    exit 1
}

if ([string]::IsNullOrEmpty($BUILD_NUMBER)) {
    Push-Location $ROOT_DIR
    try {
        $BUILD_NUMBER = git rev-list --count HEAD 2>$null
        if ($LASTEXITCODE -ne 0) { $BUILD_NUMBER = "0" }
    }
    finally {
        Pop-Location
    }
}

if ($BUILD_NUMBER -notmatch '^\d+$') {
    Write-Error "Invalid build number '$BUILD_NUMBER'. Expected digits only."
    exit 1
}

prepare_build_dir

@"
// Auto-generated by scripts/ios-write-version-xcconfig.ps1.
// Local version override; do not commit.
OPENCLAW_IOS_VERSION = $IOS_VERSION
OPENCLAW_MARKETING_VERSION = $MARKETING_VERSION
OPENCLAW_BUILD_VERSION = $BUILD_NUMBER
"@ | write_generated_file $VERSION_XCCONFIG

Write-Host "Prepared iOS version settings: ios=$IOS_VERSION marketing=$MARKETING_VERSION build=$BUILD_NUMBER"
