set -euo pipefail

# Install a prepared artifact set and derive the site's checksums from its bytes.

# Function to get absolute path
get_abs_path() {
    local path="$1"
    if [[ "$path" == /* ]]; then
        echo "$path"
    else
        echo "$(pwd)/$path"
    fi
}

# Parse arguments
FROM_DIR=""
while [[ $# -gt 0 ]]; do
    case $1 in
        --from-dir)
            FROM_DIR="$(get_abs_path "$2")"
            shift 2
            ;;
        *)
            echo "Unknown argument: $1" >&2
            exit 1
            ;;
    esac
done

if [[ -z "$FROM_DIR" ]]; then
    echo "Error: --from-dir is required" >&2
    exit 1
fi

# Determine site directory (two levels up from script location)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SITE_DIR="$(dirname "$(dirname "$SCRIPT_DIR")")"

# Read version from manifest.json
MANIFEST_PATH="$SITE_DIR/../plugin-source/browser-extension/manifest.json"
if [[ ! -f "$MANIFEST_PATH" ]]; then
    echo "Error: Manifest file not found at $MANIFEST_PATH" >&2
    exit 1
fi

VERSION=$(jq -r '.version' "$MANIFEST_PATH")
if [[ "$VERSION" == "null" ]] || [[ -z "$VERSION" ]]; then
    echo "Error: Could not extract version from manifest" >&2
    exit 1
fi

# Define artifact names
declare -a NAMES=(
    "tiktok-live-companion-extension-${VERSION}.zip"
    "tiktok-live-companion-plugin-${VERSION}.zip"
    "tiktok-live-companion-service-${VERSION}.zip"
    "tiktok-live-companion-android-${VERSION}-source.zip"
    "tiktok-live-companion-ios-${VERSION}-source.zip"
)

APK_NAME="tiktok-live-companion-android-${VERSION}.apk"
if [[ -f "$FROM_DIR/$APK_NAME" ]]; then
    NAMES+=("$APK_NAME")
fi

# Validate each ZIP file
for NAME in "${NAMES[@]}"; do
    SRC="$FROM_DIR/$NAME"
    
    if [[ ! -f "$SRC" ]]; then
        echo "Error: Source file not found: $SRC" >&2
        exit 1
    fi
    
    # Test ZIP integrity
    if ! unzip -t "$SRC" >/dev/null 2>&1; then
        echo "Error: Corrupt ZIP: $NAME" >&2
        exit 1
    fi
    
    # Check manifest version for extension files
    if [[ "$NAME" == *"extension"* ]]; then
        TEMP_MANIFEST=$(mktemp)
        trap 'rm -f "$TEMP_MANIFEST"' EXIT
        unzip -p "$SRC" "manifest.json" > "$TEMP_MANIFEST"
        EXT_VERSION=$(jq -r '.version' "$TEMP_MANIFEST")
        
        if [[ "$EXT_VERSION" != "$VERSION" ]]; then
            echo "Error: Manifest version mismatch in $NAME: expected $VERSION, got $EXT_VERSION" >&2
            exit 1
        fi
        rm -f "$TEMP_MANIFEST"
    fi
done

# Copy files to downloads directory
DOWNLOADS_DIR="$SITE_DIR/public/downloads"
mkdir -p "$DOWNLOADS_DIR"

HASHES=""
for NAME in "${NAMES[@]}"; do
    cp "$FROM_DIR/$NAME" "$DOWNLOADS_DIR/$NAME"
    
    # Calculate SHA256 hash
    HASH=$(sha256sum "$DOWNLOADS_DIR/$NAME" | cut -d' ' -f1)
    HASHES+="$HASH  $NAME"$'\n'
done

# Write hashes to SHA256.txt file
SHA_FILE="$DOWNLOADS_DIR/tiktok-live-companion-${VERSION}-SHA256.txt"
echo -n "$HASHES" > "$SHA_FILE"

# Write TypeScript file with checksums
TS_FILE="$SITE_DIR/src/download-checksums.ts"
ESCAPED_HASHES=$(printf '%q' "$HASHES")
echo "// Generated by site/scripts/sync-downloads.py; do not edit by hand." > "$TS_FILE"
echo "export const downloadChecksums = \`$HASHES\`;" >> "$TS_FILE"

# Output hashes
echo -n "$HASHES"
