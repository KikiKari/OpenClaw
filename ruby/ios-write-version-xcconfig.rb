require 'fileutils'
require 'json'
require 'open3'

def usage
  puts <<~EOF
    Usage:
      scripts/ios-write-version-xcconfig.rb [--build-number 7]

    Writes apps/ios/build/Version.xcconfig from apps/ios/version.json:
    - OPENCLAW_IOS_VERSION = exact canonical iOS version
    - OPENCLAW_MARKETING_VERSION = short iOS/App Store version
    - OPENCLAW_BUILD_VERSION = explicit build number or local numeric fallback
  EOF
end

ROOT_DIR = File.expand_path('..', __dir__)
IOS_DIR = File.join(ROOT_DIR, 'apps', 'ios')
BUILD_DIR = File.join(IOS_DIR, 'build')
VERSION_XCCONFIG = File.join(BUILD_DIR, 'Version.xcconfig')
VERSION_HELPER = File.join(ROOT_DIR, 'scripts', 'ios-version.ts')
IOS_VERSION = ''
MARKETING_VERSION = ''
BUILD_NUMBER = ''

def prepare_build_dir
  if File.symlink?(BUILD_DIR)
    $stderr.puts "Refusing to use symlinked build directory: #{BUILD_DIR}"
    exit 1
  end

  FileUtils.mkdir_p(BUILD_DIR)
end

def write_generated_file(output_path, content)
  if File.symlink?(output_path)
    $stderr.puts "Refusing to overwrite symlinked file: #{output_path}"
    exit 1
  end

  tmp_file = File.join(File.dirname(output_path), ".#{File.basename(output_path)}.tmp")
  File.write(tmp_file, content)
  FileUtils.mv(tmp_file, output_path, force: true)
end

ARGV.each_with_index do |arg, index|
  case arg
  when '--build-number'
    BUILD_NUMBER = ARGV[index + 1] || ''
    ARGV.delete_at(index + 1)
    ARGV.delete_at(index)
    break
  when '-h', '--help'
    usage
    exit 0
  else
    $stderr.puts "Unknown argument: #{arg}"
    usage
    exit 1
  end
end

stdout, _status = Open3.capture2('node', '--import', 'tsx', VERSION_HELPER, '--shell', chdir: ROOT_DIR)
stdout.each_line do |line|
  key, value = line.strip.split('=', 2)
  case key
  when 'OPENCLAW_IOS_VERSION'
    IOS_VERSION = value
  when 'OPENCLAW_MARKETING_VERSION'
    MARKETING_VERSION = value
  end
end

if IOS_VERSION.empty? || MARKETING_VERSION.empty?
  $stderr.puts "Unable to resolve iOS version metadata from #{ROOT_DIR}/apps/ios/version.json."
  exit 1
end

if BUILD_NUMBER.empty?
  stdout, _status = Open3.capture2('git', 'rev-list', '--count', 'HEAD', chdir: ROOT_DIR)
  BUILD_NUMBER = stdout.strip.empty? ? '0' : stdout.strip
end

unless BUILD_NUMBER.match?(/^\d+$/)
  $stderr.puts "Invalid build number '#{BUILD_NUMBER}'. Expected digits only."
  exit 1
end

prepare_build_dir

content = <<~EOF
  // Auto-generated by scripts/ios-write-version-xcconfig.rb.
  // Local version override; do not commit.
  OPENCLAW_IOS_VERSION = #{IOS_VERSION}
  OPENCLAW_MARKETING_VERSION = #{MARKETING_VERSION}
  OPENCLAW_BUILD_VERSION = #{BUILD_NUMBER}
EOF

write_generated_file(VERSION_XCCONFIG, content)

puts "Prepared iOS version settings: ios=#{IOS_VERSION} marketing=#{MARKETING_VERSION} build=#{BUILD_NUMBER}"
