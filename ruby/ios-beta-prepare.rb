require 'json'
require 'fileutils'
require 'uri'
require 'tmpdir'

def usage
  puts <<~EOF
    Usage:
      OPENCLAW_PUSH_RELAY_BASE_URL=https://relay.example.com \\
        scripts/ios-beta-prepare.sh --build-number 7 [--team-id TEAMID]

    Prepares local beta-release inputs without touching local signing overrides:
    - reads apps/ios/version.json and writes apps/ios/build/Version.xcconfig
    - writes apps/ios/build/BetaRelease.xcconfig with canonical bundle IDs
    - configures the beta build for relay-backed APNs registration
    - regenerates apps/ios/OpenClaw.xcodeproj via xcodegen
  EOF
end

root_dir = File.expand_path(File.join(File.dirname(__FILE__), '..'))
ios_dir = File.join(root_dir, 'apps', 'ios')
build_dir = File.join(ios_dir, 'build')
beta_xcconfig = File.join(build_dir, 'BetaRelease.xcconfig')
team_helper = File.join(root_dir, 'scripts', 'ios-team-id.sh')
version_helper = File.join(root_dir, 'scripts', 'ios-write-version-xcconfig.sh')
ios_version_helper = File.join(root_dir, 'scripts', 'ios-version.ts')
version_sync_helper = File.join(root_dir, 'scripts', 'ios-sync-versioning.ts')

build_number = ''
team_id = ENV['IOS_DEVELOPMENT_TEAM'] || ''
push_relay_base_url = ENV['OPENCLAW_PUSH_RELAY_BASE_URL'] || ENV['IOS_PUSH_RELAY_BASE_URL'] || ''
push_relay_base_url_xcconfig = ''
ios_version = ''

def prepare_build_dir(build_dir)
  if File.symlink?(build_dir)
    STDERR.puts "Refusing to use symlinked build directory: #{build_dir}"
    exit 1
  end

  FileUtils.mkdir_p(build_dir)
end

def write_generated_file(output_path)
  if File.exist?(output_path) && File.symlink?(output_path)
    STDERR.puts "Refusing to overwrite symlinked file: #{output_path}"
    exit 1
  end

  tmp_file = "#{output_path}.#{rand(36**6).to_s(36)}"
  File.open(tmp_file, 'w') { |f| yield f }
  FileUtils.mv(tmp_file, output_path, force: true)
end

def validate_push_relay_base_url(value)
  if value.match(/[[:space:]]/)
    STDERR.puts "Invalid OPENCLAW_PUSH_RELAY_BASE_URL: whitespace is not allowed."
    exit 1
  end

  if value.match(/[\$\(\)\=]/)
    STDERR.puts "Invalid OPENCLAW_PUSH_RELAY_BASE_URL: contains forbidden xcconfig characters."
    exit 1
  end

  uri = URI.parse(value)
  unless uri.is_a?(URI::HTTPS)
    STDERR.puts "Invalid OPENCLAW_PUSH_RELAY_BASE_URL: expected https://host[:port][/path]."
    exit 1
  end

  if uri.port < 1 || uri.port > 65535
    STDERR.puts "Invalid OPENCLAW_PUSH_RELAY_BASE_URL: port must be between 1 and 65535."
    exit 1
  end
rescue URI::InvalidURIError
  STDERR.puts "Invalid OPENCLAW_PUSH_RELAY_BASE_URL: expected https://host[:port][/path]."
  exit 1
end

# Parse command line arguments
args = ARGV.dup
while args.any?
  arg = args.shift
  case arg
  when '--'
    # Ignore
  when '--build-number'
    build_number = args.shift || ''
  when '--team-id'
    team_id = args.shift || ''
  when '-h', '--help'
    usage
    exit 0
  else
    STDERR.puts "Unknown argument: #{arg}"
    usage
    exit 1
  end
end

if build_number.empty?
  STDERR.puts "Missing required --build-number."
  usage
  exit 1
end

if team_id.empty?
  team_id = `IOS_ALLOW_KEYCHAIN_TEAM_FALLBACK=1 bash "#{team_helper}"`.strip
end

if team_id.empty?
  STDERR.puts "Could not resolve Apple Team ID. Set IOS_DEVELOPMENT_TEAM or sign into Xcode."
  exit 1
end

if push_relay_base_url.empty?
  STDERR.puts "Missing OPENCLAW_PUSH_RELAY_BASE_URL (or IOS_PUSH_RELAY_BASE_URL) for beta relay registration."
  exit 1
end

validate_push_relay_base_url(push_relay_base_url)

# `.xcconfig` treats `//` as a comment opener. Break the URL with a helper setting
# so Xcode still resolves it back to `https://...` at build time.
push_relay_base_url_xcconfig = push_relay_base_url.gsub('//', '$(OPENCLAW_URL_SLASH)$(OPENCLAW_URL_SLASH)')

prepare_build_dir(build_dir)

Dir.chdir(root_dir) do
  system("node", "--import", "tsx", version_sync_helper, "--check")
end

ios_version = `cd "#{root_dir}" && node --import tsx "#{ios_version_helper}" --field canonicalVersion`.strip
if ios_version.empty?
  STDERR.puts "Unable to resolve iOS version from #{File.join(root_dir, 'apps', 'ios', 'version.json')}."
  exit 1
end

system("bash \"#{version_helper}\" --build-number \"#{build_number}\"")

write_generated_file(beta_xcconfig) do |f|
  f.puts <<~EOF
    // Auto-generated by scripts/ios-beta-prepare.sh.
    // Local beta-release override; do not commit.
    OPENCLAW_CODE_SIGN_STYLE = Automatic
    OPENCLAW_DEVELOPMENT_TEAM = #{team_id}
    OPENCLAW_IOS_SELECTED_TEAM = #{team_id}
    OPENCLAW_APP_BUNDLE_ID = ai.openclaw.client
    OPENCLAW_SHARE_BUNDLE_ID = ai.openclaw.client.share
    OPENCLAW_ACTIVITY_WIDGET_BUNDLE_ID = ai.openclaw.client.activitywidget
    OPENCLAW_WATCH_APP_BUNDLE_ID = ai.openclaw.client.watchkitapp
    OPENCLAW_WATCH_EXTENSION_BUNDLE_ID = ai.openclaw.client.watchkitapp.extension
    OPENCLAW_APP_PROFILE =
    OPENCLAW_SHARE_PROFILE =
    OPENCLAW_PUSH_TRANSPORT = relay
    OPENCLAW_PUSH_DISTRIBUTION = official
    OPENCLAW_URL_SLASH = /
    OPENCLAW_PUSH_RELAY_BASE_URL = #{push_relay_base_url_xcconfig}
    OPENCLAW_PUSH_APNS_ENVIRONMENT = production
  EOF
end

Dir.chdir(ios_dir) do
  system('xcodegen', 'generate')
end

puts "Prepared iOS beta release: version=#{ios_version} build=#{build_number} team=#{team_id}"
puts "XCODE_XCCONFIG_FILE=#{beta_xcconfig}"
