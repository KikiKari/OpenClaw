require 'fileutils'
require 'pathname'
require 'securerandom'
require 'tempfile'

def sanitize_identifier_segment(raw)
  raw = raw.to_s.downcase
  raw = raw.gsub(/[^a-z0-9]+/, '-')
  raw = raw.gsub(/^-+/, '')
  raw = raw.gsub(/-+$/, '')
  raw = raw.gsub(/-+/, '-')
  raw = 'local' if raw.empty?
  raw
end

def normalize_bundle_id(raw)
  raw = raw.to_s.downcase
  raw = raw.gsub(/[^a-z0-9.\-]+/, '-')
  raw = raw.gsub(/\.\.+/, '.')
  raw = raw.gsub(/^-+/, '')
  raw = raw.gsub(/[.\-]+$/, '')
  raw = 'ai.openclaw.ios.test.local' if raw.empty?
  raw
end

# Determine script paths
root_dir = Pathname.new(__FILE__).dirname.parent.to_s
ios_dir = File.join(root_dir, 'apps', 'ios')
team_id_script = File.join(root_dir, 'scripts', 'ios-team-id.sh')
local_signing_file = File.join(ios_dir, '.local-signing.xcconfig')

# Check if team ID script exists and is executable
unless File.executable?(team_id_script)
  STDERR.puts "ERROR: Missing team detection helper: #{team_id_script}"
  exit 1
end

# Get team ID
team_id = ''
begin
  team_id = `#{team_id_script}`.strip
rescue StandardError
  # If team ID script fails
  if ENV['IOS_SIGNING_REQUIRED'] == '1'
    system(team_id_script)
    exit 1
  end

  STDERR.puts 'WARN: Unable to detect an Apple Team ID; keeping existing iOS signing override (if any).'
  exit 0
end

# Determine identity source for bundle suffix
if !ENV['OPENCLAW_IOS_BUNDLE_SUFFIX'].to_s.empty?
  identity_source = ENV['OPENCLAW_IOS_BUNDLE_SUFFIX']
else
  identity_source = ENV['USER'] || ''
  if identity_source.empty?
    identity_source = `id -un`.strip rescue ''
  end
  team_segment = sanitize_identifier_segment(team_id)
  identity_source = "#{identity_source}-#{team_segment}"
end

bundle_suffix = sanitize_identifier_segment(identity_source)

# Determine base bundle ID
bundle_base = ENV['OPENCLAW_IOS_APP_BUNDLE_ID'] || ENV['OPENCLAW_IOS_BUNDLE_ID_BASE'] || ''
if bundle_base.empty?
  bundle_base = "ai.openclaw.ios.test.#{bundle_suffix}"
end
bundle_base = normalize_bundle_id(bundle_base)

# Determine other bundle IDs
share_bundle_id = ENV['OPENCLAW_IOS_SHARE_BUNDLE_ID'] || "#{bundle_base}.share"
activity_widget_bundle_id = ENV['OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID'] || "#{bundle_base}.activitywidget"
watch_app_bundle_id = ENV['OPENCLAW_IOS_WATCH_APP_BUNDLE_ID'] || "#{bundle_base}.watchkitapp"
watch_extension_bundle_id = ENV['OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID'] || "#{watch_app_bundle_id}.extension"

# Signing configuration values
code_sign_style = ENV['OPENCLAW_IOS_CODE_SIGN_STYLE'] || 'Automatic'
app_profile = ENV['OPENCLAW_IOS_APP_PROFILE'] || ''
share_profile = ENV['OPENCLAW_IOS_SHARE_PROFILE'] || ''
watch_app_profile = ENV['OPENCLAW_IOS_WATCH_APP_PROFILE'] || ''
watch_extension_profile = ENV['OPENCLAW_IOS_WATCH_EXTENSION_PROFILE'] || ''

# Create temporary file with configuration content
content = <<~EOF
  // Auto-generated by scripts/ios-configure-signing.sh.
  // This file is local-only and should not be committed.
  // Override values with env vars if needed:
  // OPENCLAW_IOS_APP_BUNDLE_ID / OPENCLAW_IOS_BUNDLE_ID_BASE
  // OPENCLAW_IOS_SHARE_BUNDLE_ID / OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID
  // OPENCLAW_IOS_WATCH_APP_BUNDLE_ID / OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID
  // OPENCLAW_IOS_CODE_SIGN_STYLE / OPENCLAW_IOS_APP_PROFILE / OPENCLAW_IOS_SHARE_PROFILE
  // OPENCLAW_IOS_WATCH_APP_PROFILE / OPENCLAW_IOS_WATCH_EXTENSION_PROFILE
  OPENCLAW_CODE_SIGN_STYLE = #{code_sign_style}
  OPENCLAW_DEVELOPMENT_TEAM = #{team_id}
  // Keep legacy key for compatibility with older signing config paths.
  OPENCLAW_IOS_SELECTED_TEAM = #{team_id}
  OPENCLAW_APP_BUNDLE_ID = #{bundle_base}
  OPENCLAW_SHARE_BUNDLE_ID = #{share_bundle_id}
  OPENCLAW_ACTIVITY_WIDGET_BUNDLE_ID = #{activity_widget_bundle_id}
  OPENCLAW_WATCH_APP_BUNDLE_ID = #{watch_app_bundle_id}
  OPENCLAW_WATCH_EXTENSION_BUNDLE_ID = #{watch_extension_bundle_id}
  OPENCLAW_APP_PROFILE = #{app_profile}
  OPENCLAW_SHARE_PROFILE = #{share_profile}
  OPENCLAW_WATCH_APP_PROFILE = #{watch_app_profile}
  OPENCLAW_WATCH_EXTENSION_PROFILE = #{watch_extension_profile}
EOF

# Check if existing file is the same
if File.exist?(local_signing_file) && File.read(local_signing_file) == content
  puts "iOS signing config already up to date: team=#{team_id} app=#{bundle_base}"
  exit 0
end

# Write new configuration file
File.write(local_signing_file, content)
puts "Configured iOS signing: team=#{team_id} app=#{bundle_base}"
