# Install a prepared artifact set and derive the site's checksums from its bytes.
require 'json'
require 'digest'
require 'fileutils'
require 'zip'

parser = OptionParser.new
parser.on('--from-dir DIR', String, 'Source directory') { |v| options[:from_dir] = v }
options = {}
parser.parse!

site = File.expand_path(File.join(File.dirname(__FILE__), '..'))
manifest_path = File.join(site, '..', 'plugin-source', 'browser-extension', 'manifest.json')
version = JSON.parse(File.read(manifest_path, encoding: 'UTF-8'))['version']

names = []
[['extension', ''], ['plugin', ''], ['service', ''], ['android', '-source'], ['ios', '-source']].each do |kind, suffix|
  names << "tiktok-live-companion-#{kind}-#{version}#{suffix}.zip"
end

apk_name = "tiktok-live-companion-android-#{version}.apk"
if File.file?(File.join(options[:from_dir], apk_name))
  names << apk_name
end

names.each do |name|
  src = File.join(options[:from_dir], name)
  Zip::File.open(src) do |z|
    unless z.entries.all? { |entry| entry.ftype == :file }
      raise "Corrupt ZIP: #{name}"
    end
    if name.include?('extension')
      manifest_content = z.read('manifest.json')
      manifest_version = JSON.parse(manifest_content)['version']
      if manifest_version != version
        raise "Manifest version mismatch"
      end
    end
  end
end

names.each do |name|
  src = File.join(options[:from_dir], name)
  dest = File.join(site, 'public', 'downloads', name)
  FileUtils.cp(src, dest, preserve: true)
end

hashes = ''
names.each do |name|
  file_path = File.join(site, 'public', 'downloads', name)
  sha256 = Digest::SHA256.file(file_path).hexdigest
  hashes += "#{sha256}  #{name}\n"
end

checksum_file = File.join(site, 'public', 'downloads', "tiktok-live-companion-#{version}-SHA256.txt")
File.write(checksum_file, hashes, encoding: 'UTF-8')

ts_content = "// Generated by site/scripts/sync-downloads.py; do not edit by hand.\nexport const downloadChecksums = #{JSON.generate(hashes)};\n"
ts_file = File.join(site, 'src', 'download-checksums.ts')
File.write(ts_file, ts_content, encoding: 'UTF-8')

puts hashes
