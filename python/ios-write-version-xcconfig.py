import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

def usage():
    print("""Usage:
  scripts/ios-write-version-xcconfig.py [--build-number 7]

Writes apps/ios/build/Version.xcconfig from apps/ios/version.json:
- OPENCLAW_IOS_VERSION = exact canonical iOS version
- OPENCLAW_MARKETING_VERSION = short iOS/App Store version
- OPENCLAW_BUILD_VERSION = explicit build number or local numeric fallback""")

def prepare_build_dir(build_dir_path):
    """Ensure build directory exists and is not a symlink"""
    build_dir = Path(build_dir_path)
    
    if build_dir.is_symlink():
        print(f"Refusing to use symlinked build directory: {build_dir}", file=sys.stderr)
        sys.exit(1)
    
    build_dir.mkdir(parents=True, exist_ok=True)

def write_generated_file(output_path, content):
    """Write content to file, ensuring it's not overwriting a symlink"""
    output_file = Path(output_path)
    
    if output_file.exists() and output_file.is_symlink():
        print(f"Refusing to overwrite symlinked file: {output_file}", file=sys.stderr)
        sys.exit(1)
    
    # Create temporary file and atomically replace target
    with tempfile.NamedTemporaryFile(mode='w', dir=output_file.parent, 
                                   prefix=output_file.name + '.', 
                                   suffix='', delete=False) as tmp_file:
        tmp_file.write(content)
        tmp_path = tmp_file.name
    
    # Atomically replace the target file
    os.replace(tmp_path, output_path)

def main():
    parser = argparse.ArgumentParser(description='Write iOS version xcconfig file')
    parser.add_argument('--build-number', type=str, help='Explicit build number')
    parser.add_argument('-h', '--help', action='store_true', help='Show help')
    args = parser.parse_args()
    
    if args.help:
        usage()
        sys.exit(0)
    
    build_number = args.build_number
    
    # Determine root directory
    script_dir = Path(__file__).parent.resolve()
    root_dir = script_dir.parent
    ios_dir = root_dir / "apps" / "ios"
    build_dir = ios_dir / "build"
    version_xcconfig = ios_dir / "build" / "Version.xcconfig"
    version_helper = root_dir / "scripts" / "ios-version.ts"
    
    ios_version = ""
    marketing_version = ""
    
    # Run node script to get version info
    try:
        result = subprocess.run([
            'node', '--import', 'tsx', str(version_helper), '--shell'
        ], cwd=root_dir, capture_output=True, text=True, check=True)
        
        for line in result.stdout.splitlines():
            if '=' in line:
                key, value = line.split('=', 1)
                key = key.strip()
                value = value.strip()
                
                if key == 'OPENCLAW_IOS_VERSION':
                    ios_version = value
                elif key == 'OPENCLAW_MARKETING_VERSION':
                    marketing_version = value
                    
    except subprocess.CalledProcessError as e:
        print(f"Failed to run version helper: {e}", file=sys.stderr)
        sys.exit(1)
    
    if not ios_version or not marketing_version:
        print(f"Unable to resolve iOS version metadata from {root_dir}/apps/ios/version.json.", file=sys.stderr)
        sys.exit(1)
    
    # Get build number from git if not provided
    if not build_number:
        try:
            result = subprocess.run([
                'git', 'rev-list', '--count', 'HEAD'
            ], cwd=root_dir, capture_output=True, text=True, check=True)
            build_number = result.stdout.strip()
        except (subprocess.CalledProcessError, FileNotFoundError):
            build_number = '0'
    
    # Validate build number format
    if not re.match(r'^[0-9]+$', build_number):
        print(f"Invalid build number '{build_number}'. Expected digits only.", file=sys.stderr)
        sys.exit(1)
    
    # Prepare build directory
    prepare_build_dir(build_dir)
    
    # Generate xcconfig content
    xcconfig_content = f"""// Auto-generated by scripts/ios-write-version-xcconfig.py.
// Local version override; do not commit.
OPENCLAW_IOS_VERSION = {ios_version}
OPENCLAW_MARKETING_VERSION = {marketing_version}
OPENCLAW_BUILD_VERSION = {build_number}
"""
    
    # Write the file
    write_generated_file(version_xcconfig, xcconfig_content)
    
    print(f"Prepared iOS version settings: ios={ios_version} marketing={marketing_version} build={build_number}")

if __name__ == '__main__':
    main()
