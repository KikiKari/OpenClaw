import os
import sys
import subprocess
import tempfile
import shutil
import getpass

def sanitize_identifier_segment(raw):
    if not raw:
        raw = ""
    raw = raw.lower()
    import re
    raw = re.sub(r'[^a-z0-9]+', '-', raw)
    raw = re.sub(r'^-+', '', raw)
    raw = re.sub(r'-+$', '', raw)
    raw = re.sub(r'-+', '-', raw)
    if not raw:
        raw = "local"
    return raw

def normalize_bundle_id(raw):
    if not raw:
        raw = ""
    raw = raw.lower()
    import re
    raw = re.sub(r'[^a-z0-9.-]+', '-', raw)
    raw = re.sub(r'\.+', '.', raw)
    raw = re.sub(r'^-+', '', raw)
    raw = re.sub(r'[.-]+$', '', raw)
    if not raw:
        raw = "ai.openclaw.ios.test.local"
    return raw

def main():
    root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    ios_dir = os.path.join(root_dir, "apps", "ios")
    team_id_script = os.path.join(root_dir, "scripts", "ios-team-id.sh")
    local_signing_file = os.path.join(ios_dir, ".local-signing.xcconfig")

    if not os.path.isfile(team_id_script) or not os.access(team_id_script, os.X_OK):
        print(f"ERROR: Missing team detection helper: {team_id_script}", file=sys.stderr)
        sys.exit(1)

    team_id = ""
    try:
        result = subprocess.run([team_id_script], capture_output=True, text=True, check=True)
        team_id = result.stdout.strip()
    except subprocess.CalledProcessError:
        if os.environ.get("IOS_SIGNING_REQUIRED", "0") == "1":
            subprocess.run([team_id_script])
            sys.exit(1)
        print("WARN: Unable to detect an Apple Team ID; keeping existing iOS signing override (if any).", file=sys.stderr)
        sys.exit(0)

    if os.environ.get("OPENCLAW_IOS_BUNDLE_SUFFIX"):
        identity_source = os.environ["OPENCLAW_IOS_BUNDLE_SUFFIX"]
    else:
        identity_source = os.environ.get("USER", "")
        if not identity_source:
            try:
                identity_source = subprocess.check_output(["id", "-un"], text=True).strip()
            except subprocess.CalledProcessError:
                pass
        team_segment = sanitize_identifier_segment(team_id)
        identity_source = f"{identity_source}-{team_segment}"
    bundle_suffix = sanitize_identifier_segment(identity_source)

    bundle_base = os.environ.get("OPENCLAW_IOS_APP_BUNDLE_ID", os.environ.get("OPENCLAW_IOS_BUNDLE_ID_BASE", ""))
    if not bundle_base:
        bundle_base = f"ai.openclaw.ios.test.{bundle_suffix}"
    bundle_base = normalize_bundle_id(bundle_base)

    share_bundle_id = os.environ.get("OPENCLAW_IOS_SHARE_BUNDLE_ID", f"{bundle_base}.share")
    activity_widget_bundle_id = os.environ.get("OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID", f"{bundle_base}.activitywidget")
    watch_app_bundle_id = os.environ.get("OPENCLAW_IOS_WATCH_APP_BUNDLE_ID", f"{bundle_base}.watchkitapp")
    watch_extension_bundle_id = os.environ.get("OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID", f"{watch_app_bundle_id}.extension")

    code_sign_style = os.environ.get("OPENCLAW_IOS_CODE_SIGN_STYLE", "Automatic")
    app_profile = os.environ.get("OPENCLAW_IOS_APP_PROFILE", "")
    share_profile = os.environ.get("OPENCLAW_IOS_SHARE_PROFILE", "")
    watch_app_profile = os.environ.get("OPENCLAW_IOS_WATCH_APP_PROFILE", "")
    watch_extension_profile = os.environ.get("OPENCLAW_IOS_WATCH_EXTENSION_PROFILE", "")

    content = f"""// Auto-generated by scripts/ios-configure-signing.sh.
// This file is local-only and should not be committed.
// Override values with env vars if needed:
// OPENCLAW_IOS_APP_BUNDLE_ID / OPENCLAW_IOS_BUNDLE_ID_BASE
// OPENCLAW_IOS_SHARE_BUNDLE_ID / OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID
// OPENCLAW_IOS_WATCH_APP_BUNDLE_ID / OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID
// OPENCLAW_IOS_CODE_SIGN_STYLE / OPENCLAW_IOS_APP_PROFILE / OPENCLAW_IOS_SHARE_PROFILE
// OPENCLAW_IOS_WATCH_APP_PROFILE / OPENCLAW_IOS_WATCH_EXTENSION_PROFILE
OPENCLAW_CODE_SIGN_STYLE = {code_sign_style}
OPENCLAW_DEVELOPMENT_TEAM = {team_id}
// Keep legacy key for compatibility with older signing config paths.
OPENCLAW_IOS_SELECTED_TEAM = {team_id}
OPENCLAW_APP_BUNDLE_ID = {bundle_base}
OPENCLAW_SHARE_BUNDLE_ID = {share_bundle_id}
OPENCLAW_ACTIVITY_WIDGET_BUNDLE_ID = {activity_widget_bundle_id}
OPENCLAW_WATCH_APP_BUNDLE_ID = {watch_app_bundle_id}
OPENCLAW_WATCH_EXTENSION_BUNDLE_ID = {watch_extension_bundle_id}
OPENCLAW_APP_PROFILE = {app_profile}
OPENCLAW_SHARE_PROFILE = {share_profile}
OPENCLAW_WATCH_APP_PROFILE = {watch_app_profile}
OPENCLAW_WATCH_EXTENSION_PROFILE = {watch_extension_profile}
"""

    tmp_file = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', delete=False, dir=os.environ.get('TMPDIR', '/tmp'), suffix='.xcconfig') as f:
            tmp_file = f.name
            f.write(content)

        if os.path.exists(local_signing_file):
            import filecmp
            if filecmp.cmp(tmp_file, local_signing_file):
                os.unlink(tmp_file)
                print(f"iOS signing config already up to date: team={team_id} app={bundle_base}")
                return

        shutil.move(tmp_file, local_signing_file)
        print(f"Configured iOS signing: team={team_id} app={bundle_base}")
    finally:
        if tmp_file and os.path.exists(tmp_file):
            os.unlink(tmp_file)

if __name__ == "__main__":
    main()
