--[[Install a prepared artifact set and derive the site's checksums from its bytes.]]
local argparse = require "argparse"
local json = require "cjson"
local sha2 = require "sha2"
local zip = require "zip"

local function read_file(path)
  local file = io.open(path, "rb")
  if not file then return nil end
  local content = file:read("*all")
  file:close()
  return content
end

local function write_file(path, content)
  local file = io.open(path, "wb")
  file:write(content)
  file:close()
end

local function copy_file(src, dst)
  local content = read_file(src)
  if content then
    write_file(dst, content)
  end
end

local parser = argparse.ArgumentParser()
parser:add_argument("--from-dir", { required = true })
local args = parser:parse()

-- Simulate Path(__file__).resolve().parents[1] by getting script directory
local script_path = arg[0] or "."
local site = script_path:gsub("/[^/]*$", ""):gsub("/[^/]*$", "")

local manifest_path = site .. "/../plugin-source/browser-extension/manifest.json"
local manifest_content = read_file(manifest_path)
local manifest = json.decode(manifest_content)
local version = manifest.version

local kinds = {
  {"extension", ""},
  {"plugin", ""},
  {"service", ""},
  {"android", "-source"},
  {"ios", "-source"}
}

local names = {}
for _, v in ipairs(kinds) do
  local kind, suffix = v[1], v[2]
  table.insert(names, "tiktok-live-companion-" .. kind .. "-" .. version .. suffix .. ".zip")
end

local apk_name = "tiktok-live-companion-android-" .. version .. ".apk"
if io.open(args.from_dir .. "/" .. apk_name, "r") then
  table.insert(names, apk_name)
end

-- Validate ZIP files
for _, name in ipairs(names) do
  local src = args.from_dir .. "/" .. name
  local zfile, err = zip.open(src)
  if not zfile then
    error("Cannot open ZIP: " .. name .. " - " .. (err or ""))
  end
  
  -- Test ZIP integrity (basic check)
  local entries = 0
  for entry in zfile:files() do
    entries = entries + 1
    -- Try to read a bit of each file to test integrity
    local f = zfile:open(entry.filename)
    if f then f:read(1024) f:close() end
  end
  
  if entries == 0 then
    error("Empty or corrupt ZIP: " .. name)
  end
  
  -- Check manifest version for extension
  if name:find("extension") then
    local manifest_entry = zfile:open("manifest.json")
    if manifest_entry then
      local manifest_data = manifest_entry:read("*a")
      manifest_entry:close()
      if manifest_data then
        local zip_manifest = json.decode(manifest_data)
        if zip_manifest.version ~= version then
          error("Manifest version mismatch")
        end
      end
    end
  end
  zfile:close()
end

-- Copy files
for _, name in ipairs(names) do
  local src = args.from_dir .. "/" .. name
  local dst = site .. "/public/downloads/" .. name
  copy_file(src, dst)
end

-- Generate hashes
local hashes = ""
for _, name in ipairs(names) do
  local content = read_file(site .. "/public/downloads/" .. name)
  local hash = sha2.sha256(content)
  hashes = hashes .. hash .. "  " .. name .. "\n"
end

-- Write checksum file
local checksum_file = site .. "/public/downloads/tiktok-live-companion-" .. version .. "-SHA256.txt"
write_file(checksum_file, hashes)

-- Write TypeScript file
local ts_content = "// Generated by site/scripts/sync-downloads.py; do not edit by hand.\nexport const downloadChecksums = " .. json.encode(hashes) .. ";\n"
local ts_file = site .. "/src/download-checksums.ts"
write_file(ts_file, ts_content)

print(hashes)
