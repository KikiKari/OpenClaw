local lfs = require "lfs"

local function usage()
  io.write([[
Usage:
  scripts/ios-write-version-xcconfig.lua [--build-number 7]

Writes apps/ios/build/Version.xcconfig from apps/ios/version.json:
- OPENCLAW_IOS_VERSION = exact canonical iOS version
- OPENCLAW_MARKETING_VERSION = short iOS/App Store version
- OPENCLAW_BUILD_VERSION = explicit build number or local numeric fallback
]])
end

local function get_script_dir()
  local str = debug.getinfo(2, "S").source:sub(2)
  return str:match("(.*/)")
end

local ROOT_DIR = lfs.currentdir() .. "/.."
local IOS_DIR = ROOT_DIR .. "/apps/ios"
local BUILD_DIR = IOS_DIR .. "/build"
local VERSION_XCCONFIG = IOS_DIR .. "/build/Version.xcconfig"
local VERSION_HELPER = ROOT_DIR .. "/scripts/ios-version.ts"
local IOS_VERSION = ""
local MARKETING_VERSION = ""
local BUILD_NUMBER = ""

local function prepare_build_dir()
  if lfs.symlinkattributes(BUILD_DIR, "mode") then
    io.stderr:write("Refusing to use symlinked build directory: " .. BUILD_DIR .. "\n")
    os.exit(1)
  end

  lfs.mkdir(BUILD_DIR)
end

local function write_generated_file(output_path, content)
  if lfs.symlinkattributes(output_path, "mode") then
    io.stderr:write("Refusing to overwrite symlinked file: " .. output_path .. "\n")
    os.exit(1)
  end

  local tmp_file = os.tmpname()
  local file = io.open(tmp_file, "w")
  file:write(content)
  file:close()
  os.rename(tmp_file, output_path)
end

local args = {...}
local i = 1
while i <= #args do
  if args[i] == "--" then
    i = i + 1
  elseif args[i] == "--build-number" then
    BUILD_NUMBER = args[i+1] or ""
    i = i + 2
  elseif args[i] == "-h" or args[i] == "--help" then
    usage()
    os.exit(0)
  else
    io.stderr:write("Unknown argument: " .. args[i] .. "\n")
    usage()
    os.exit(1)
  end
end

local handle = io.popen("cd " .. ROOT_DIR .. " && node --import tsx " .. VERSION_HELPER .. " --shell")
for line in handle:lines() do
  local key, value = line:match("^([^=]+)=(.*)$")
  if key == "OPENCLAW_IOS_VERSION" then
    IOS_VERSION = value
  elseif key == "OPENCLAW_MARKETING_VERSION" then
    MARKETING_VERSION = value
  end
end
handle:close()

if IOS_VERSION == "" or MARKETING_VERSION == "" then
  io.stderr:write("Unable to resolve iOS version metadata from " .. ROOT_DIR .. "/apps/ios/version.json.\n")
  os.exit(1)
end

if BUILD_NUMBER == "" then
  handle = io.popen("cd " .. ROOT_DIR .. " && git rev-list --count HEAD 2>/dev/null || printf '0'")
  BUILD_NUMBER = handle:read("*a"):gsub("%s+", "")
  handle:close()
end

if not BUILD_NUMBER:match("^[0-9]+$") then
  io.stderr:write("Invalid build number '" .. BUILD_NUMBER .. "'. Expected digits only.\n")
  os.exit(1)
end

prepare_build_dir()

local content = [[
// Auto-generated by scripts/ios-write-version-xcconfig.lua.
// Local version override; do not commit.
OPENCLAW_IOS_VERSION = ]] .. IOS_VERSION .. [[
OPENCLAW_MARKETING_VERSION = ]] .. MARKETING_VERSION .. [[
OPENCLAW_BUILD_VERSION = ]] .. BUILD_NUMBER .. [[
]]

write_generated_file(VERSION_XCCONFIG, content)

io.write("Prepared iOS version settings: ios=" .. IOS_VERSION .. " marketing=" .. MARKETING_VERSION .. " build=" .. BUILD_NUMBER .. "\n")
