local function sanitize_identifier_segment(raw)
  if not raw or raw == "" then
    return "local"
  end
  
  raw = string.lower(raw)
  raw = string.gsub(raw, "[^%w]+", "-")
  raw = string.gsub(raw, "^-+", "")
  raw = string.gsub(raw, "-+$", "")
  raw = string.gsub(raw, "-+", "-")
  
  if raw == "" then
    return "local"
  end
  
  return raw
end

local function normalize_bundle_id(raw)
  if not raw or raw == "" then
    return "ai.openclaw.ios.test.local"
  end
  
  raw = string.lower(raw)
  raw = string.gsub(raw, "[^%w%.%-]+", "-")
  raw = string.gsub(raw, "%.+", ".")
  raw = string.gsub(raw, "^-+", "")
  raw = string.gsub(raw, "[%.%-]+$", "")
  
  if raw == "" then
    return "ai.openclaw.ios.test.local"
  end
  
  return raw
end

-- Get script directory and paths
local script_path = arg[0] or "./"
local root_dir = script_path:gsub("/scripts/[^/]*$", ""):gsub("/+", "/")
if root_dir == "" then root_dir = ".." end
local ios_dir = root_dir .. "/apps/ios"
local team_id_script = root_dir .. "/scripts/ios-team-id.sh"
local local_signing_file = ios_dir .. "/.local-signing.xcconfig"

-- Check if team ID script exists and is executable
local stat = require("posix.sys.stat")
if not stat.stat(team_id_script) or not stat.S_IXUSR then
  io.stderr:write("ERROR: Missing team detection helper: " .. team_id_script .. "\n")
  os.exit(1)
end

-- Execute team ID script
local team_id = nil
local handle = io.popen(team_id_script .. " 2>/dev/null", "r")
if handle then
  team_id = handle:read("*l")
  handle:close()
end

if not team_id or team_id == "" then
  local ios_signing_required = os.getenv("IOS_SIGNING_REQUIRED") or "0"
  if ios_signing_required == "1" then
    os.execute(team_id_script)
    os.exit(1)
  end
  
  io.stderr:write("WARN: Unable to detect an Apple Team ID; keeping existing iOS signing override (if any).\n")
  os.exit(0)
end

-- Determine identity source
local identity_source
local openclaw_ios_bundle_suffix = os.getenv("OPENCLAW_IOS_BUNDLE_SUFFIX")
if openclaw_ios_bundle_suffix and openclaw_ios_bundle_suffix ~= "" then
  identity_source = openclaw_ios_bundle_suffix
else
  identity_source = os.getenv("USER") or ""
  if identity_source == "" then
    local f = io.popen("id -un 2>/dev/null", "r")
    if f then
      identity_source = f:read("*l") or ""
      f:close()
    end
  end
  local team_segment = sanitize_identifier_segment(team_id)
  identity_source = identity_source .. "-" .. team_segment
end

local bundle_suffix = sanitize_identifier_segment(identity_source)

-- Determine bundle base
local bundle_base = os.getenv("OPENCLAW_IOS_APP_BUNDLE_ID") or os.getenv("OPENCLAW_IOS_BUNDLE_ID_BASE") or ""
if bundle_base == "" then
  bundle_base = "ai.openclaw.ios.test." .. bundle_suffix
end
bundle_base = normalize_bundle_id(bundle_base)

-- Determine other bundle IDs
local share_bundle_id = os.getenv("OPENCLAW_IOS_SHARE_BUNDLE_ID") or (bundle_base .. ".share")
local activity_widget_bundle_id = os.getenv("OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID") or (bundle_base .. ".activitywidget")
local watch_app_bundle_id = os.getenv("OPENCLAW_IOS_WATCH_APP_BUNDLE_ID") or (bundle_base .. ".watchkitapp")
local watch_extension_bundle_id = os.getenv("OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID") or (watch_app_bundle_id .. ".extension")

-- Get profile settings
local code_sign_style = os.getenv("OPENCLAW_IOS_CODE_SIGN_STYLE") or "Automatic"
local app_profile = os.getenv("OPENCLAW_IOS_APP_PROFILE") or ""
local share_profile = os.getenv("OPENCLAW_IOS_SHARE_PROFILE") or ""
local watch_app_profile = os.getenv("OPENCLAW_IOS_WATCH_APP_PROFILE") or ""
local watch_extension_profile = os.getenv("OPENCLAW_IOS_WATCH_EXTENSION_PROFILE") or ""

-- Create temporary file content
local tmp_content = [[// Auto-generated by scripts/ios-configure-signing.sh.
// This file is local-only and should not be committed.
// Override values with env vars if needed:
// OPENCLAW_IOS_APP_BUNDLE_ID / OPENCLAW_IOS_BUNDLE_ID_BASE
// OPENCLAW_IOS_SHARE_BUNDLE_ID / OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID
// OPENCLAW_IOS_WATCH_APP_BUNDLE_ID / OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID
// OPENCLAW_IOS_CODE_SIGN_STYLE / OPENCLAW_IOS_APP_PROFILE / OPENCLAW_IOS_SHARE_PROFILE
// OPENCLAW_IOS_WATCH_APP_PROFILE / OPENCLAW_IOS_WATCH_EXTENSION_PROFILE
OPENCLAW_CODE_SIGN_STYLE = ]] .. code_sign_style .. [[
OPENCLAW_DEVELOPMENT_TEAM = ]] .. team_id .. [[
// Keep legacy key for compatibility with older signing config paths.
OPENCLAW_IOS_SELECTED_TEAM = ]] .. team_id .. [[
OPENCLAW_APP_BUNDLE_ID = ]] .. bundle_base .. [[
OPENCLAW_SHARE_BUNDLE_ID = ]] .. share_bundle_id .. [[
OPENCLAW_ACTIVITY_WIDGET_BUNDLE_ID = ]] .. activity_widget_bundle_id .. [[
OPENCLAW_WATCH_APP_BUNDLE_ID = ]] .. watch_app_bundle_id .. [[
OPENCLAW_WATCH_EXTENSION_BUNDLE_ID = ]] .. watch_extension_bundle_id .. [[
OPENCLAW_APP_PROFILE = ]] .. app_profile .. [[
OPENCLAW_SHARE_PROFILE = ]] .. share_profile .. [[
OPENCLAW_WATCH_APP_PROFILE = ]] .. watch_app_profile .. [[
OPENCLAW_WATCH_EXTENSION_PROFILE = ]] .. watch_extension_profile .. "\n"

-- Write to temporary file
local tmpdir = os.getenv("TMPDIR") or "/tmp"
local tmp_file = tmpdir .. "/openclaw-ios-signing.tmp"
local f = io.open(tmp_file, "w")
if f then
  f:write(tmp_content)
  f:close()
else
  io.stderr:write("ERROR: Could not create temporary file\n")
  os.exit(1)
end

-- Check if file already exists and compare content
local file_exists = false
local same_content = false
local current_content = ""

if io.open(local_signing_file, "r") then
  file_exists = true
  local f = io.open(local_signing_file, "r")
  if f then
    current_content = f:read("*a")
    f:close()
    if current_content == tmp_content then
      same_content = true
    end
  end
end

if file_exists and same_content then
  os.remove(tmp_file)
  print("iOS signing config already up to date: team=" .. team_id .. " app=" .. bundle_base)
  os.exit(0)
end

-- Move temp file to destination
os.rename(tmp_file, local_signing_file)
print("Configured iOS signing: team=" .. team_id .. " app=" .. bundle_base)
