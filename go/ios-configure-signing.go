package main

import (
	"bufio"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

func main() {
	if len(os.Args) > 1 && os.Args[1] == "-h" {
		fmt.Println("Usage: ios-configure-signing.go")
		os.Exit(0)
	}

	rootDir := filepath.Join(filepath.Dir(os.Args[0]), "..")
	iosDir := filepath.Join(rootDir, "apps", "ios")
	teamIdScript := filepath.Join(rootDir, "scripts", "ios-team-id.sh")
	localSigningFile := filepath.Join(iosDir, ".local-signing.xcconfig")

	if _, err := os.Stat(teamIdScript); os.IsNotExist(err) {
		fmt.Fprintf(os.Stderr, "ERROR: Missing team detection helper: %s\n", teamIdScript)
		os.Exit(1)
	}

	var teamId string
	cmd := exec.Command(teamIdScript)
	output, err := cmd.CombinedOutput()
	if err != nil {
		if os.Getenv("IOS_SIGNING_REQUIRED") == "1" {
			fmt.Fprint(os.Stderr, string(output))
			os.Exit(1)
		}
		fmt.Fprintln(os.Stderr, "WARN: Unable to detect an Apple Team ID; keeping existing iOS signing override (if any).")
		os.Exit(0)
	}
	teamId = strings.TrimSpace(string(output))

	var identitySource string
	if bundleSuffix := os.Getenv("OPENCLAW_IOS_BUNDLE_SUFFIX"); bundleSuffix != "" {
		identitySource = bundleSuffix
	} else {
		identitySource = os.Getenv("USER")
		if identitySource == "" {
			identitySource = getCurrentUser()
		}
		teamSegment := sanitizeIdentifierSegment(teamId)
		identitySource = fmt.Sprintf("%s-%s", identitySource, teamSegment)
	}
	bundleSuffix := sanitizeIdentifierSegment(identitySource)

	bundleBase := os.Getenv("OPENCLAW_IOS_APP_BUNDLE_ID")
	if bundleBase == "" {
		bundleBase = os.Getenv("OPENCLAW_IOS_BUNDLE_ID_BASE")
	}
	if bundleBase == "" {
		bundleBase = fmt.Sprintf("ai.openclaw.ios.test.%s", bundleSuffix)
	}
	bundleBase = normalizeBundleId(bundleBase)

	shareBundleId := os.Getenv("OPENCLAW_IOS_SHARE_BUNDLE_ID")
	if shareBundleId == "" {
		shareBundleId = fmt.Sprintf("%s.share", bundleBase)
	}
	
	activityWidgetBundleId := os.Getenv("OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID")
	if activityWidgetBundleId == "" {
		activityWidgetBundleId = fmt.Sprintf("%s.activitywidget", bundleBase)
	}
	
	watchAppBundleId := os.Getenv("OPENCLAW_IOS_WATCH_APP_BUNDLE_ID")
	if watchAppBundleId == "" {
		watchAppBundleId = fmt.Sprintf("%s.watchkitapp", bundleBase)
	}
	
	watchExtensionBundleId := os.Getenv("OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID")
	if watchExtensionBundleId == "" {
		watchExtensionBundleId = fmt.Sprintf("%s.extension", watchAppBundleId)
	}

	codeSignStyle := os.Getenv("OPENCLAW_IOS_CODE_SIGN_STYLE")
	if codeSignStyle == "" {
		codeSignStyle = "Automatic"
	}
	
	appProfile := os.Getenv("OPENCLAW_IOS_APP_PROFILE")
	shareProfile := os.Getenv("OPENCLAW_IOS_SHARE_PROFILE")
	watchAppProfile := os.Getenv("OPENCLAW_IOS_WATCH_APP_PROFILE")
	watchExtensionProfile := os.Getenv("OPENCLAW_IOS_WATCH_EXTENSION_PROFILE")

	tmpFile, err := os.CreateTemp(os.TempDir(), "openclaw-ios-signing.*")
	if err != nil {
		panic(err)
	}
	defer os.Remove(tmpFile.Name())

	content := fmt.Sprintf(`// Auto-generated by scripts/ios-configure-signing.sh.
// This file is local-only and should not be committed.
// Override values with env vars if needed:
// OPENCLAW_IOS_APP_BUNDLE_ID / OPENCLAW_IOS_BUNDLE_ID_BASE
// OPENCLAW_IOS_SHARE_BUNDLE_ID / OPENCLAW_IOS_ACTIVITY_WIDGET_BUNDLE_ID
// OPENCLAW_IOS_WATCH_APP_BUNDLE_ID / OPENCLAW_IOS_WATCH_EXTENSION_BUNDLE_ID
// OPENCLAW_IOS_CODE_SIGN_STYLE / OPENCLAW_IOS_APP_PROFILE / OPENCLAW_IOS_SHARE_PROFILE
// OPENCLAW_IOS_WATCH_APP_PROFILE / OPENCLAW_IOS_WATCH_EXTENSION_PROFILE
OPENCLAW_CODE_SIGN_STYLE = %s
OPENCLAW_DEVELOPMENT_TEAM = %s
// Keep legacy key for compatibility with older signing config paths.
OPENCLAW_IOS_SELECTED_TEAM = %s
OPENCLAW_APP_BUNDLE_ID = %s
OPENCLAW_SHARE_BUNDLE_ID = %s
OPENCLAW_ACTIVITY_WIDGET_BUNDLE_ID = %s
OPENCLAW_WATCH_APP_BUNDLE_ID = %s
OPENCLAW_WATCH_EXTENSION_BUNDLE_ID = %s
OPENCLAW_APP_PROFILE = %s
OPENCLAW_SHARE_PROFILE = %s
OPENCLAW_WATCH_APP_PROFILE = %s
OPENCLAW_WATCH_EXTENSION_PROFILE = %s
`, codeSignStyle, teamId, teamId, bundleBase, shareBundleId, activityWidgetBundleId,
		watchAppBundleId, watchExtensionBundleId, appProfile, shareProfile,
		watchAppProfile, watchExtensionProfile)

	if _, err := tmpFile.WriteString(content); err != nil {
		panic(err)
	}
	tmpFile.Close()

	if equal, _ := filesEqual(tmpFile.Name(), localSigningFile); equal {
		fmt.Printf("iOS signing config already up to date: team=%s app=%s\n", teamId, bundleBase)
		return
	}

	if err := os.Rename(tmpFile.Name(), localSigningFile); err != nil {
		panic(err)
	}
	fmt.Printf("Configured iOS signing: team=%s app=%s\n", teamId, bundleBase)
}

func sanitizeIdentifierSegment(raw string) string {
	re := regexp.MustCompile("[^a-z0-9]+")
	result := strings.ToLower(raw)
	result = re.ReplaceAllString(result, "-")
	result = strings.Trim(result, "-")
	result = regexp.MustCompile("-+").ReplaceAllString(result, "-")
	if result == "" {
		result = "local"
	}
	return result
}

func normalizeBundleId(raw string) string {
	re := regexp.MustCompile("[^a-z0-9.-]+")
	result := strings.ToLower(raw)
	result = re.ReplaceAllString(result, "-")
	result = regexp.MustCompile("\\.+").ReplaceAllString(result, ".")
	result = strings.TrimPrefix(result, "-")
	result = strings.TrimSuffix(result, ".")
	result = strings.TrimSuffix(result, "-")
	if result == "" {
		result = "ai.openclaw.ios.test.local"
	}
	return result
}

func getCurrentUser() string {
	if user := os.Getenv("USER"); user != "" {
		return user
	}
	cmd := exec.Command("id", "-un")
	output, err := cmd.Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(output))
}

func filesEqual(file1, file2 string) (bool, error) {
	f1, err := os.Open(file1)
	if err != nil {
		return false, err
	}
	defer f1.Close()

	f2, err := os.Open(file2)
	if err != nil {
		return false, err
	}
	defer f2.Close()

	r1 := bufio.NewReader(f1)
	r2 := bufio.NewReader(f2)

	for {
		b1, err1 := r1.ReadByte()
		b2, err2 := r2.ReadByte()

		if err1 != nil || err2 != nil {
			return err1 == io.EOF && err2 == io.EOF, nil
		}

		if b1 != b2 {
			return false, nil
		}
	}
}
