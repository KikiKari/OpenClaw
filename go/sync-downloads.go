// Install a prepared artifact set and derive the site's checksums from its bytes.
package main

import (
	"archive/zip"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	fromDir := os.Args[1]
	if fromDir == "" {
		panic("Missing --from-dir argument")
	}

	// Get site path (two levels up from this script's directory)
	wd, _ := os.Getwd()
	site := filepath.Dir(filepath.Dir(wd))

	// Read manifest to get version
	manifestPath := filepath.Join(site, "..", "plugin-source", "browser-extension", "manifest.json")
	manifestBytes, err := os.ReadFile(manifestPath)
	if err != nil {
		panic(err)
	}

	var manifest map[string]interface{}
	err = json.Unmarshal(manifestBytes, &manifest)
	if err != nil {
		panic(err)
	}
	version := manifest["version"].(string)

	// Define artifact names
	kinds := []struct {
		kind   string
		suffix string
	}{
		{"extension", ""},
		{"plugin", ""},
		{"service", ""},
		{"android", "-source"},
		{"ios", "-source"},
	}

	var names []string
	for _, k := range kinds {
		name := fmt.Sprintf("tiktok-live-companion-%s-%s%s.zip", k.kind, version, k.suffix)
		names = append(names, name)
	}

	// Check if APK exists and add to names if it does
	apkName := fmt.Sprintf("tiktok-live-companion-android-%s.apk", version)
	if _, err := os.Stat(filepath.Join(fromDir, apkName)); err == nil {
		names = append(names, apkName)
	}

	// Validate each ZIP file
	for _, name := range names {
		if !strings.HasSuffix(name, ".zip") {
			continue
		}
		src := filepath.Join(fromDir, name)
		reader, err := zip.OpenReader(src)
		if err != nil {
			panic("Cannot open ZIP: " + name + " - " + err.Error())
		}
		defer reader.Close()

		// Test ZIP integrity
		for _, f := range reader.File {
			rc, err := f.Open()
			if err != nil {
				panic("Corrupt ZIP: " + name)
			}
			_, err = io.Copy(io.Discard, rc)
			rc.Close()
			if err != nil {
				panic("Corrupt ZIP: " + name)
			}
		}

		// Check manifest version for extension
		if strings.Contains(name, "extension") {
			manifestFile, err := reader.Open("manifest.json")
			if err != nil {
				panic("Missing manifest.json in: " + name)
			}
			defer manifestFile.Close()

			manifestData, err := io.ReadAll(manifestFile)
			if err != nil {
				panic("Cannot read manifest.json in: " + name)
			}

			var zipManifest map[string]interface{}
			err = json.Unmarshal(manifestData, &zipManifest)
			if err != nil {
				panic("Invalid JSON in manifest.json: " + name)
			}

			if zipManifest["version"] != version {
				panic("Manifest version mismatch in: " + name)
			}
		}
	}

	// Copy files to public/downloads
	downloadsDir := filepath.Join(site, "public", "downloads")
	os.MkdirAll(downloadsDir, 0755)

	for _, name := range names {
		src := filepath.Join(fromDir, name)
		dst := filepath.Join(downloadsDir, name)
		copyFile(src, dst)
	}

	// Generate SHA256 hashes
	var hashes strings.Builder
	for _, name := range names {
		filePath := filepath.Join(downloadsDir, name)
		hash := calculateSHA256(filePath)
		hashes.WriteString(hash + "  " + name + "\n")
	}

	// Write hashes to text file
	hashFileName := fmt.Sprintf("tiktok-live-companion-%s-SHA256.txt", version)
	hashFilePath := filepath.Join(downloadsDir, hashFileName)
	err = os.WriteFile(hashFilePath, []byte(hashes.String()), 0644)
	if err != nil {
		panic(err)
	}

	// Write TypeScript file
	tsContent := "// Generated by site/scripts/sync-downloads.go; do not edit by hand.\nexport const downloadChecksums = " + 
		fmt.Sprintf("%q", hashes.String()) + ";\n"
	tsPath := filepath.Join(site, "src", "download-checksums.ts")
	err = os.WriteFile(tsPath, []byte(tsContent), 0644)
	if err != nil {
		panic(err)
	}

	fmt.Print(hashes.String())
}

func copyFile(src, dst string) {
	source, err := os.Open(src)
	if err != nil {
		panic(err)
	}
	defer source.Close()

	destination, err := os.Create(dst)
	if err != nil {
		panic(err)
	}
	defer destination.Close()

	_, err = io.Copy(destination, source)
	if err != nil {
		panic(err)
	}
	
	// Copy file permissions
	info, _ := source.Stat()
	destination.Chmod(info.Mode())
}

func calculateSHA256(filePath string) string {
	file, err := os.Open(filePath)
	if err != nil {
		panic(err)
	}
	defer file.Close()

	hasher := sha256.New()
	if _, err := io.Copy(hasher, file); err != nil {
		panic(err)
	}

	return hex.EncodeToString(hasher.Sum(nil))
}
