package main

import (
	"bufio"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

const usage = `Usage:
  scripts/ios-write-version-xcconfig.sh [--build-number 7]

Writes apps/ios/build/Version.xcconfig from apps/ios/version.json:
- OPENCLAW_IOS_VERSION = exact canonical iOS version
- OPENCLAW_MARKETING_VERSION = short iOS/App Store version
- OPENCLAW_BUILD_VERSION = explicit build number or local numeric fallback`

func main() {
	buildNumber := flag.String("build-number", "", "explicit build number")
	flag.Usage = func() {
		fmt.Println(usage)
	}
	flag.Parse()

	rootDir, err := filepath.Abs(filepath.Join(filepath.Dir(os.Args[0]), ".."))
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error getting root directory: %v\n", err)
		os.Exit(1)
	}

	iosDir := filepath.Join(rootDir, "apps", "ios")
	buildDir := filepath.Join(iosDir, "build")
	versionXcconfig := filepath.Join(buildDir, "Version.xcconfig")
	versionHelper := filepath.Join(rootDir, "scripts", "ios-version.ts")

	iosVersion, marketingVersion, err := getVersionInfo(rootDir, versionHelper)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error getting version info: %v\n", err)
		os.Exit(1)
	}

	if *buildNumber == "" {
		*buildNumber, err = getBuildNumber(rootDir)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Error getting build number: %v\n", err)
			os.Exit(1)
		}
	}

	if !regexp.MustCompile(`^\d+$`).MatchString(*buildNumber) {
		fmt.Fprintf(os.Stderr, "Invalid build number '%s'. Expected digits only.\n", *buildNumber)
		os.Exit(1)
	}

	if err := prepareBuildDir(buildDir); err != nil {
		fmt.Fprintf(os.Stderr, "Error preparing build directory: %v\n", err)
		os.Exit(1)
	}

	if err := writeGeneratedFile(versionXcconfig, iosVersion, marketingVersion, *buildNumber); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing generated file: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Prepared iOS version settings: ios=%s marketing=%s build=%s\n", iosVersion, marketingVersion, *buildNumber)
}

func getVersionInfo(rootDir, versionHelper string) (string, string, error) {
	cmd := exec.Command("node", "--import", "tsx", versionHelper, "--shell")
	cmd.Dir = rootDir
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		return "", "", err
	}

	if err := cmd.Start(); err != nil {
		return "", "", err
	}

	iosVersion, marketingVersion := "", ""
	scanner := bufio.NewScanner(stdout)
	for scanner.Scan() {
		line := scanner.Text()
		parts := strings.SplitN(line, "=", 2)
		if len(parts) != 2 {
			continue
		}
		key, value := parts[0], parts[1]
		switch key {
		case "OPENCLAW_IOS_VERSION":
			iosVersion = value
		case "OPENCLAW_MARKETING_VERSION":
			marketingVersion = value
		}
	}

	if err := scanner.Err(); err != nil {
		return "", "", err
	}

	if err := cmd.Wait(); err != nil {
		return "", "", err
	}

	if iosVersion == "" || marketingVersion == "" {
		return "", "", fmt.Errorf("unable to resolve iOS version metadata from %s/apps/ios/version.json", rootDir)
	}

	return iosVersion, marketingVersion, nil
}

func getBuildNumber(rootDir string) (string, error) {
	cmd := exec.Command("git", "rev-list", "--count", "HEAD")
	cmd.Dir = rootDir
	output, err := cmd.Output()
	if err != nil {
		return "0", nil
	}
	return strings.TrimSpace(string(output)), nil
}

func prepareBuildDir(buildDir string) error {
	if isSymlink(buildDir) {
		return fmt.Errorf("refusing to use symlinked build directory: %s", buildDir)
	}

	if err := os.MkdirAll(buildDir, 0755); err != nil {
		return err
	}

	return nil
}

func isSymlink(path string) bool {
	fi, err := os.Lstat(path)
	if err != nil {
		return false
	}
	return fi.Mode()&os.ModeSymlink != 0
}

func writeGeneratedFile(outputPath, iosVersion, marketingVersion, buildNumber string) error {
	if isSymlink(outputPath) {
		return fmt.Errorf("refusing to overwrite symlinked file: %s", outputPath)
	}

	tmpFile, err := os.CreateTemp(filepath.Dir(outputPath), filepath.Base(outputPath)+".XXXXXX")
	if err != nil {
		return err
	}
	defer os.Remove(tmpFile.Name())

	content := fmt.Sprintf(`// Auto-generated by scripts/ios-write-version-xcconfig.sh.
// Local version override; do not commit.
OPENCLAW_IOS_VERSION = %s
OPENCLAW_MARKETING_VERSION = %s
OPENCLAW_BUILD_VERSION = %s
`, iosVersion, marketingVersion, buildNumber)

	if _, err := io.WriteString(tmpFile, content); err != nil {
		return err
	}

	if err := tmpFile.Close(); err != nil {
		return err
	}

	if err := os.Rename(tmpFile.Name(), outputPath); err != nil {
		return err
	}

	return nil
}
